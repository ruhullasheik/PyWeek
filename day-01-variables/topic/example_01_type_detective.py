"""Example 1: Type Detective

Run this and see what types Python infers.
"""

a = 42
b = 3.14
c = "Python"
d = True
e = None
f = [1, 2, 3]
g = (1, 2)
h = {"key": "value"}

# Print each variable and its type
print(f"a = {a}  ({type(a)})")
print(f"b = {b}  ({type(b)})")
print(f"c = {c}  ({type(c)})")
print(f"d = {d}  ({type(d)})")
print(f"e = {e}  ({type(e)})")
print(f"f = {f}  ({type(f)})")
print(f"g = {g}  ({type(g)})")
print(f"h = {h}  ({type(h)})")
